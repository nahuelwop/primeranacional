export function getRegionalClubsByRegion(
  region: RegionalRegion,
): RegionalClubSeed[] {
  return REGIONAL_CLUBS.filter(c => c.region === region);
}

export function getRegionalClubsByGroup(
  region: RegionalRegion,
  group: string,
): RegionalClubSeed[] {
  return REGIONAL_CLUBS.filter(
    c => c.region === region && c.group === group,
  );
}

export function getRegionalGroups(
  region: RegionalRegion,
): string[] {
  return Array.from(
    new Set(
      REGIONAL_CLUBS
        .filter(c => c.region === region)
        .map(c => c.group),
    ),
  ).sort((a, b) =>
    Number(a) - Number(b),
  );
}
