export type RegionalRegion =
  | "Norte"
  | "Litoral Norte"
  | "Litoral Sur"
  | "Centro"
  | "Cuyo"
  | "Pampeana Norte"
  | "Pampeana Sur"
  | "Patagonia";

export type RegionalClubSeed = {
  id: string;
  name: string;
  city: string;
  province: string;
  region: RegionalRegion;
  group: string;
  short: string;
};

const R = (
  id: string,
  name: string,
  city: string,
  province: string,
  region: RegionalRegion,
  group: string,
  short?: string,
): RegionalClubSeed => ({
  id,
  name,
  city,
  province,
  region,
  group,
  short: short ?? shortCode(name),
});

function shortCode(name: string): string {
  const clean = name
    .replace(/\([^)]*\)/g, "")
    .replace(/\b(Atl\.?|Club|Deportivo|Sportivo|C\.A\.I)\b/gi, "")
    .replace(/\s+/g, " ")
    .trim();

  const words = clean.split(/\s+/).filter(Boolean);

  if (words.length === 0) return "???";
  if (words.length === 1) return words[0].slice(0, 3).toUpperCase();

  return words
    .slice(0, 3)
    .map(w => w[0])
    .join("")
    .slice(0, 3)
    .toUpperCase();
}

